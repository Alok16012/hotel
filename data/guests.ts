/**
 * The in-house tail.
 *
 * Roughly two thirds of a hotel's occupied rooms on any given night belong to
 * people who never touched the CRM: OTA bookings, walk-ins, repeat guests who
 * phoned the desk. They carry no open enquiry and no conversation thread, but
 * they do occupy rooms and they do count towards occupancy and revenue. Leaving
 * them out would make the property look two-thirds empty.
 */
function houseGuest(
  id: string,
  name: string,
  phone: string,
  city: string,
  stays: number,
  lifetimeValue: number,
  extra: Partial<Guest> = {},
): Guest {
  return {
    id,
    name,
    phone,
    city,
    segments: stays > 1 ? ["returning"] : ["new"],
    totalStays: stays,
    lifetimeValue,
    preferences: [],
    tags: [],
    lastInteractionAt: daysAgo(1),
    createdAt: daysAgo(stays > 1 ? 180 + stays * 24 : 9),
    ...extra,
  };
}

