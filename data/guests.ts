/**
 * People with a room held on a future date and no stay behind them yet.
 *
 * They exist because the forward book has to belong to somebody. A hotel three
 * weeks out is mostly strangers, and the availability screen would be dishonest
 * if every committed room traced back to a guest already in the building.
 *
 * Stay count and lifetime value are zero on purpose. These are reservations,
 * not history, and a guest directory that credits a stay before the guest has
 * arrived would overstate every segment it feeds.
 */
function futureGuest(
  id: string,
  name: string,
  phone: string,
  city: string,
  bookedAgo: number,
  extra: Partial<Guest> = {},
): Guest {
  return {
    id,
    name,
    phone,
    city,
    segments: ["new"],
    totalStays: 0,
    lifetimeValue: 0,
    preferences: [],
    tags: [],
    lastInteractionAt: daysAgo(bookedAgo),
    createdAt: daysAgo(bookedAgo),
    ...extra,
  };
}

