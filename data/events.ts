/**
 * Newest first. The literals above are grouped by story so they stay readable
 * while being written; the feed reads this sorted view, so the two can never
 * disagree about what happened when.
 */
export const EVENTS: EventRecord[] = [...LOG].sort((a, b) =>
  b.occurredAt.localeCompare(a.occurredAt),
);

/** Events that happened on the demo day. */
export const EVENTS_TODAY = EVENTS.filter((e) => isDemoToday(e.occurredAt));

/**
 * Work the desk did today.
 *
 * A guest writing in is not work the desk performed, so those events are
 * excluded before the ratio is taken. Counting them would quietly depress the
 * autonomy rate every time the property had a busy morning, which is exactly
 * backwards.
 */
export const DESK_ACTIONS_TODAY = EVENTS_TODAY.filter((e) => e.actorKind !== "guest");

export const AUTONOMY_RATE =
  DESK_ACTIONS_TODAY.filter((e) => e.resolvedAutonomously).length / DESK_ACTIONS_TODAY.length;

/** Desk actions that required a person: the eight on the other side of the ratio. */
export const HUMAN_TOUCHED_TODAY = DESK_ACTIONS_TODAY.filter((e) => !e.resolvedAutonomously);
